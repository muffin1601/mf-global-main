const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const request = require('supertest');
const mongoose = require('mongoose');
const bcrypt = require('bcrypt');
const { Resend } = require('resend');
const { MongoMemoryServer } = require('mongodb-memory-server');
const router = require('../routes/main/careersRoutes');
const Job = require('../models/CareerJob');
const Application = require('../models/CareerApplication');
const Session = require('../models/CareerSession');
let mongo;
let agent;
let csrf;
let jobId;
const app = express(); app.use(express.json()); app.use('/api', router);
const pinHash = process.env.CAREERS_ADMIN_PIN_HASH;
const resendKey = process.env.RESEND_API_KEY;
const notificationEmails = process.env.CAREERS_NOTIFICATION_EMAILS;
const resendEmailPrototype = Object.getPrototypeOf(new Resend('re_careers_test').emails);
const originalSend = resendEmailPrototype.send;
let sentEmails = [];
test.before(async () => { mongo = await MongoMemoryServer.create(); await mongoose.connect(mongo.getUri()); process.env.CAREERS_ADMIN_PIN_HASH = await bcrypt.hash('123456', 4); process.env.RESEND_API_KEY = 're_careers_test'; process.env.CAREERS_NOTIFICATION_EMAILS = 'sales@mfglobalservices.com,faruk@mfglobalservices.com'; resendEmailPrototype.send = async email => { sentEmails.push(email); return { data: { id: 'test-email-id' }, error: null }; }; agent = request.agent(app); });
test.after(async () => { resendEmailPrototype.send = originalSend; await mongoose.disconnect(); await mongo?.stop(); if (pinHash === undefined) delete process.env.CAREERS_ADMIN_PIN_HASH; else process.env.CAREERS_ADMIN_PIN_HASH = pinHash; if (resendKey === undefined) delete process.env.RESEND_API_KEY; else process.env.RESEND_API_KEY = resendKey; if (notificationEmails === undefined) delete process.env.CAREERS_NOTIFICATION_EMAILS; else process.env.CAREERS_NOTIFICATION_EMAILS = notificationEmails; });
test('PIN authentication, CSRF, job lifecycle, applications, and private resume', async () => {
  assert.equal((await request(app).get('/api/careers/admin/jobs')).status, 401);
  assert.equal((await agent.post('/api/careers/admin/login').send({pin:'000000'})).status, 401);
  const login = await agent.post('/api/careers/admin/login').send({pin:'123456'});
  assert.equal(login.status, 200); csrf = login.body.csrfToken;
  assert.equal((await agent.post('/api/careers/admin/jobs').send({})).status, 403);
  const job = { title:'Engineer', department:'Technology', location:'Delhi', employmentType:'Full-time', workMode:'Hybrid', experience:'2 years', vacancies:1, description:'Build products', responsibilities:'Build', qualifications:'Degree', skills:'JavaScript', deadline:new Date(Date.now()+86400000).toISOString(), status:'Active', isPublished:true };
  const created = await agent.post('/api/careers/admin/jobs').set('x-csrf-token',csrf).send(job);
  assert.equal(created.status, 201); jobId=created.body._id;
  assert.equal((await request(app).get('/api/careers/jobs')).body.total, 1);
  const applied = await request(app).post('/api/careers/apply').field('jobId',jobId).field('fullName','Test Applicant').field('email','test@example.com').field('phone','9876543210').field('location','Delhi').field('experience','3 years').field('noticePeriod','30 days').field('consent','true').field('submissionKey','12345678-1234-1234-1234-123456789abc').attach('resume',Buffer.from('%PDF-1.7\nTest'),{filename:'resume.pdf',contentType:'application/pdf'});
  assert.equal(applied.status, 201); assert.ok(applied.body.applicationId);
  assert.equal(await Application.countDocuments(), 1);
  assert.deepEqual(sentEmails.map(email => email.to).sort(), ['faruk@mfglobalservices.com', 'sales@mfglobalservices.com']);
  assert.ok(sentEmails.every(email => email.text.includes(`Application ID: ${applied.body.applicationId}`)));
  assert.ok(sentEmails.every(email => !email.attachments));
  const duplicate = await request(app).post('/api/careers/apply').field('jobId',jobId).field('fullName','Test Applicant').field('email','test@example.com').field('phone','9876543210').field('location','Delhi').field('experience','3 years').field('noticePeriod','30 days').field('consent','true').field('submissionKey','12345678-1234-1234-1234-123456789abc').attach('resume',Buffer.from('%PDF-1.7\nTest'),{filename:'resume.pdf',contentType:'application/pdf'});
  assert.equal(duplicate.status, 200);
  assert.equal(sentEmails.length, 2);
  assert.equal((await request(app).get(`/api/careers/admin/applications/${applied.body.applicationId}/resume`)).status, 401);
  assert.equal((await agent.get(`/api/careers/admin/applications/${applied.body.applicationId}/resume`)).status, 200);
  assert.equal((await agent.patch(`/api/careers/admin/applications/${applied.body.applicationId}`).set('x-csrf-token',csrf).send({status:'Shortlisted'})).body.status, 'Shortlisted');
  const scheduled = await agent.put(`/api/careers/admin/jobs/${jobId}`).set('x-csrf-token',csrf).send({opensAt:new Date(Date.now()+86400000).toISOString()});
  assert.equal(scheduled.status, 200);
  assert.equal((await request(app).get('/api/careers/jobs')).body.total, 1);
  const early = await request(app).post('/api/careers/apply').field('jobId',jobId).field('fullName','Early Applicant').field('email','early@example.com').field('phone','9876543210').field('location','Delhi').field('experience','3 years').field('noticePeriod','30 days').field('consent','true').field('submissionKey','aaaaaaaa-1234-1234-1234-123456789abc').attach('resume',Buffer.from('%PDF-1.7\nTest'),{filename:'resume.pdf',contentType:'application/pdf'});
  assert.equal(early.status, 409);
  assert.equal(await Application.countDocuments(), 1);
  assert.equal((await agent.put(`/api/careers/admin/jobs/${jobId}`).set('x-csrf-token',csrf).send({isPublished:false})).status, 200);
  assert.equal((await request(app).get('/api/careers/jobs')).body.total, 0);
  assert.equal((await agent.delete(`/api/careers/admin/jobs/${jobId}`).set('x-csrf-token',csrf)).status, 200);
  assert.equal(await Job.countDocuments({archivedAt:{$ne:null}}), 1);
  assert.equal(await Application.countDocuments(), 1);
  assert.equal((await agent.post('/api/careers/admin/logout').set('x-csrf-token',csrf)).status, 200);
  assert.equal((await agent.get('/api/careers/admin/jobs')).status, 401);
});
test('locks out repeated wrong PINs and expires idle sessions', async () => {
  const other = request.agent(app);
  for (let i = 0; i < 4; i++) assert.equal((await other.post('/api/careers/admin/login').send({pin:'000000'})).status, 401);
  assert.equal((await other.post('/api/careers/admin/login').send({pin:'000000'})).status, 429);
  assert.equal((await other.post('/api/careers/admin/login').send({pin:'123456'})).status, 429);
  const Attempt = require('../models/CareerLoginAttempt');
  await Attempt.deleteMany({});
  const login = await other.post('/api/careers/admin/login').send({pin:'123456'});
  assert.equal(login.status, 200);
  await Session.updateMany({}, {expiresAt:new Date(Date.now()-1000)});
  assert.equal((await other.get('/api/careers/admin/jobs')).status, 401);
});
