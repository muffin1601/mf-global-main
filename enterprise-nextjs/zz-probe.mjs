import { launch, signedIn, base } from "./tests/e2e/lib.mjs";
const b = await launch();
const ctx = await signedIn(b, null);
const p = await ctx.newPage();
p.on("pageerror", e => console.log("pageerror", String(e).slice(0,150)));
p.on("console", m => m.type()==="error" && console.log("console", m.text().slice(0,120)));
await p.goto(base + "/");
const btn = p.locator("header.navbar").getByRole("button", { name: "Our Products" });
await btn.click();
await p.waitForTimeout(300);
console.log("after mouse click expanded:", await btn.getAttribute("aria-expanded"));
await p.mouse.move(5, 600); await p.waitForTimeout(300);
console.log("after leave:", await btn.getAttribute("aria-expanded"));
await p.goto(base + "/blogs/new");
await p.locator("input[name=title]").fill("anon post");
await p.locator("textarea[name=content]").fill("anon content");
const [r] = await Promise.all([p.waitForResponse(r => r.url().includes("/api/blogs/post-blogs")), p.getByRole("button", { name: "Post Blog" }).click()]);
await p.waitForTimeout(1500);
console.log("status", r.status(), p.url(), (await p.locator("main").innerText()).slice(0,200).replace(/\s+/g," "));
await b.close();
